/// Runs one build tool and panics with its whole output on failure.
pub fn run_tool(tool: &Path, arguments: &[String], step: &str) {
    let output = Command::new(tool)
        .args(arguments)
        .output()
        .unwrap_or_else(|error| panic!("failed to launch {}: {error}", tool.display()));
    if !output.status.success() {
        panic!(
            "{step} failed with {}\nstdout:\n{}\nstderr:\n{}",
            output.status,
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr),
        );
    }
}

/// Builds the freestanding Windows harness from `ebpf-probes/` into
/// `target/<root_name>/<name>/`, applying the mutation (if any) to
/// `lsm_enforcer.bpf.c` first and appending `defines` to the compile line.
///
/// Panics if the patch does not match exactly one span: a mutation that
/// silently failed to apply would make its negative test pass for the wrong
/// reason, which is worse than not having the test.
pub fn build_harness(
    root_name: &str,
    name: &str,
    mutation: Option<(&str, &str)>,
    defines: &[&str],
) -> PathBuf {
    let root = toolchain::repo_root();
    let probes = root.join("ebpf-probes");
    let directory = root.join("target").join(root_name).join(name);
    std::fs::create_dir_all(directory.join("ebpf-shim")).expect("create the build directory");

    let original = std::fs::read_to_string(probes.join("lsm_enforcer.bpf.c"))
        .expect("read lsm_enforcer.bpf.c");
    let source = match mutation {
        None => original,
        Some((old, new)) => {
            let matches = original.matches(old).count();
            assert_eq!(
                matches, 1,
                "the {name} patch must match exactly one span of lsm_enforcer.bpf.c, found {matches}"
            );
            original.replacen(old, new, 1)
        }
    };
    std::fs::write(directory.join("lsm_enforcer.bpf.c"), &source).expect("write enforcer source");
    std::fs::copy(
        probes.join("aegis_userspace_shim.c"),
        directory.join("aegis_userspace_shim.c"),
    )
    .expect("copy harness source");
    std::fs::copy(
        probes.join("ebpf-shim").join("aegis_shim.h"),
        directory.join("ebpf-shim").join("aegis_shim.h"),
    )
    .expect("copy shim header");

    // The freestanding build imports kernel32 functions; the import library
    // is generated here rather than shipped, so the build has no binary
    // inputs beyond the sources and the pinned LLVM. `ReadFile` and
    // `GetLastError` are referenced only by the `-DAEGIS_SHIM_BATCH` build,
    // and unused exports in the import library cost nothing for the fixture
    // build.
    let definition = directory.join("kernel32.def");
    std::fs::write(
        &definition,
        "LIBRARY kernel32.dll\nEXPORTS\n    GetStdHandle\n    WriteFile\n    ReadFile\n    GetLastError\n    ExitProcess\n",
    )
    .expect("write kernel32.def");
    let import_library = directory.join("kernel32.lib");
    run_tool(
        &toolchain::require_llvm_tool("llvm-dlltool"),
        &[
            "-m".into(),
            "arm64".into(),
            "-d".into(),
            definition.display().to_string(),
            "-l".into(),
            import_library.display().to_string(),
        ],
        "llvm-dlltool",
    );

    let object = directory.join("harness.obj");
    let mut arguments: Vec<String> = vec![
        "--target=aarch64-pc-windows-msvc".into(),
        "-O1".into(),
        "-ffreestanding".into(),
        "-fno-builtin".into(),
        "-Wall".into(),
        "-Werror".into(),
    ];
    arguments.extend(defines.iter().map(|define| format!("-D{define}")));
    arguments.push("-c".into());
    arguments.push(directory.join("aegis_userspace_shim.c").display().to_string());
    arguments.push("-o".into());
    arguments.push(object.display().to_string());
    run_tool(&toolchain::require_llvm_tool("clang"), &arguments, "clang");

    let executable = directory.join("aegis-shim.exe");
    run_tool(
        &toolchain::require_llvm_tool("lld-link"),
        &[
            "/entry:aegis_start".into(),
            "/subsystem:console".into(),
            "/nodefaultlib".into(),
            object.display().to_string(),
            import_library.display().to_string(),
            format!("/out:{}", executable.display()),
        ],
        "lld-link",
    );

    executable
}

/// Builds and runs one harness build with an empty stdin, returning the
/// parsed report and the wall-clock duration of the process.
pub fn run_executable(executable: &Path, stdin: Option<&[u8]>) -> (Run, Duration) {
    let started = Instant::now();
    let mut child = Command::new(executable)
        // `output()` would close stdin; the batch build needs it writable.
        .stdin(if stdin.is_some() { Stdio::piped() } else { Stdio::null() })
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .unwrap_or_else(|error| panic!("failed to run {}: {error}", executable.display()));
    if let Some(bytes) = stdin {
        let mut handle = child.stdin.take().expect("piped stdin");
        let bytes = bytes.to_vec();
        // A pipe holds only ~64 KiB and the child may flush output while the
        // script is still being written; a writer thread keeps a ~1 MiB script
        // and a ~1 MiB report from deadlocking against each other.
        std::thread::spawn(move || {
            let _ = handle.write_all(&bytes);
        });
    }
    let output = child
        .wait_with_output()
        .unwrap_or_else(|error| panic!("failed to wait for {}: {error}", executable.display()));
    let duration = started.elapsed();
    let stdout = String::from_utf8_lossy(&output.stdout).into_owned();
    (parse_harness_output(&stdout, output.status.code()), duration)
}

/// Builds `name` and runs it with an empty stdin.
pub fn run_harness(
    root_name: &str,
    name: &str,
    mutation: Option<(&str, &str)>,
    defines: &[&str],
) -> Run {
    let executable = build_harness(root_name, name, mutation, defines);
    run_executable(&executable, None).0
}

