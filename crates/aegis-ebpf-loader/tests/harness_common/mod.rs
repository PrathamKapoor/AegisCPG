/// The task name all replays run as. The C harness only checks the event's
/// comm starts with `a` (the kernel helper stub reports `aegis-shim`).
pub const COMM: &str = "aegis-shim";

/// Which LSM hook a probe is for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CaseHook {
    /// `bprm_check_security`: may this binary execute?
    Bprm,
    /// `file_open`: may this open proceed?
    FileOpen,
    /// `socket_connect`: may this egress?
    Socket,
}

impl CaseHook {
    /// Parses the wire word the harness prints.
    pub fn from_word(word: &str) -> CaseHook {
        match word {
            "bprm" => CaseHook::Bprm,
            "file_open" => CaseHook::FileOpen,
            "socket" => CaseHook::Socket,
            other => panic!("unknown hook `{other}`"),
        }
    }

    /// The `AEGIS_HOOK_*` code the event carries.
    pub fn code(self) -> u64 {
        match self {
            CaseHook::Bprm => 1,
            CaseHook::FileOpen => 2,
            CaseHook::Socket => 3,
        }
    }

    /// The simulator's hook enum for the same hook.
    pub fn event_hook(self) -> HookType {
        match self {
            CaseHook::Bprm => HookType::BprmCheckSecurity,
            CaseHook::FileOpen => HookType::FileOpen,
            CaseHook::Socket => HookType::SocketConnect,
        }
    }
}

/// One syscall probe, parsed from a `CASE`/`BATCH` line or generated by a
/// test. Every field is a fact the three engines must interpret identically.
#[derive(Debug, Clone)]
pub struct Case {
    pub number: u64,
    pub hook: CaseHook,
    pub cgroup: u64,
    pub ino: u64,
    pub sha: String,
    pub flags: u64,
    pub path: String,
    pub family: u64,
    pub addr: u64,
    /// The verdict the C hook printed for this probe. `None` for a probe the
    /// test generated itself: nothing has decided it yet.
    pub allow: Option<bool>,
}

impl Case {
    /// A generated `bprm_check_security` probe.
    pub fn bprm(number: u64, cgroup: u64, ino: u64, sha: impl Into<String>) -> Case {
        Case {
            number,
            hook: CaseHook::Bprm,
            cgroup,
            ino,
            sha: sha.into(),
            flags: 0,
            path: String::new(),
            family: 0,
            addr: 0,
            allow: None,
        }
    }

    /// A generated `file_open` probe.
    pub fn file_open(number: u64, cgroup: u64, flags: u64, path: impl Into<String>) -> Case {
        Case {
            number,
            hook: CaseHook::FileOpen,
            cgroup,
            ino: 0,
            sha: String::new(),
            flags,
            path: path.into(),
            family: 0,
            addr: 0,
            allow: None,
        }
    }

    /// A generated `socket_connect` probe. `addr` is the low-byte-first
    /// integer the report, the kernel map, and the VM context all use.
    pub fn socket(number: u64, cgroup: u64, family: u64, addr: u64) -> Case {
        Case {
            number,
            hook: CaseHook::Socket,
            cgroup,
            ino: 0,
            sha: String::new(),
            flags: 0,
            path: String::new(),
            family,
            addr,
            allow: None,
        }
    }
}

/// One `EVENT` line: what the C hook reported it decided.
#[derive(Debug, Clone)]
pub struct EventLine {
    pub hook_type: u64,
    pub verdict: i64,
    pub cgroup: u64,
    pub target: String,
}

/// The harness's own bottom line.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Selftest {
    Ok,
    Failed(u64),
}

/// One policy-map print: `(cgroup, allow_mask, deny_mask, level, mode)`.
pub type PolicyEntry = (u64, u32, u32, u32, u32);
/// One trie print: `(prefix bits, allow, owning cgroup, path)`.
pub type LpmEntry = (u32, u32, u64, String);
/// One net-map print: `(cgroup, address)`.
pub type NetEntry = (u64, u64);
/// One exec-registry print: `(cgroup, inode, sha256-prefix)`.
pub type ExecEntry = (u64, u64, String);

/// A parsed harness report.
#[derive(Debug)]
pub struct Run {
    pub status: Option<i32>,
    pub policies: Vec<PolicyEntry>,
    pub lpm: Vec<LpmEntry>,
    pub net: Vec<NetEntry>,
    pub exec: Vec<ExecEntry>,
    pub cases: Vec<Case>,
    /// The `BATCH` lines of a batch build, in script order. Each is a `Case`
    /// whose `allow` is the verdict the C hook returned for that probe.
    pub batches: Vec<Case>,
    pub events: Vec<EventLine>,
    /// The reasons of every `MISMATCH` line, in report order.
    pub mismatches: Vec<String>,
    pub selftest: Selftest,
}

/// Parses the report grammar documented at the top of
/// `aegis_userspace_shim.c`. Unrecognised lines are a hard error: a parser
/// that skips what it does not understand can watch a report change shape
/// without the test noticing, which is a fail-open of the test itself.
pub fn parse_harness_output(text: &str, status: Option<i32>) -> Run {
    let mut run = Run {
        status,
        policies: Vec::new(),
        lpm: Vec::new(),
        net: Vec::new(),
        exec: Vec::new(),
        cases: Vec::new(),
        batches: Vec::new(),
        events: Vec::new(),
        mismatches: Vec::new(),
        selftest: Selftest::Ok,
    };
    let mut shim_seen = false;
    let mut selftest_seen = false;

    for raw in text.lines() {
        let line = raw.trim_end();
        if line.is_empty() {
            continue;
        }
        if line == "SHIM aegis-ebpf-userspace 1" {
            shim_seen = true;
            continue;
        }
        if let Some(rest) = line.strip_prefix("MAP policy ") {
            let fields: Vec<u64> = rest
                .split(' ')
                .map(|token| token.parse().unwrap_or_else(|_| panic!("policy field `{token}`")))
                .collect();
            assert_eq!(fields.len(), 5, "MAP policy carries five fields: {line}");
            run.policies.push((
                fields[0],
                fields[1] as u32,
                fields[2] as u32,
                fields[3] as u32,
                fields[4] as u32,
            ));
            continue;
        }
        if let Some(rest) = line.strip_prefix("MAP lpm ") {
            let mut parts = rest.splitn(4, ' ');
            let bits: u32 = parts.next().expect("lpm bits").parse().expect("lpm bits");
            let allow: u32 = parts.next().expect("lpm allow").parse().expect("lpm allow");
            let owner: u64 = parts.next().expect("lpm owner").parse().expect("lpm owner");
            let path = parts.next().expect("lpm path").to_string();
            run.lpm.push((bits, allow, owner, path));
            continue;
        }
        if let Some(rest) = line.strip_prefix("MAP net ") {
            let fields: Vec<u64> = rest
                .split(' ')
                .map(|token| token.parse().unwrap_or_else(|_| panic!("net field `{token}`")))
                .collect();
            assert_eq!(fields.len(), 2, "MAP net carries two fields: {line}");
            run.net.push((fields[0], fields[1]));
            continue;
        }
        if let Some(rest) = line.strip_prefix("MAP exec ") {
            let mut parts = rest.splitn(3, ' ');
            let cgroup: u64 = parts.next().expect("exec cgroup").parse().expect("exec cgroup");
            let inode: u64 = parts.next().expect("exec inode").parse().expect("exec inode");
            let sha = parts.next().expect("exec digest").to_string();
            run.exec.push((cgroup, inode, sha));
            continue;
        }
        if let Some(rest) = line.strip_prefix("CASE ") {
            run.cases.push(parse_case(rest));
            continue;
        }
        if let Some(rest) = line.strip_prefix("BATCH ") {
            run.batches.push(parse_case(rest));
            continue;
        }
        if let Some(rest) = line.strip_prefix("EVENT ") {
            let mut parts = rest.splitn(4, ' ');
            let hook_type: u64 = parts.next().expect("event hook").parse().expect("event hook");
            let verdict: i64 = parts.next().expect("event verdict").parse().expect("event verdict");
            let cgroup: u64 = parts.next().expect("event cgroup").parse().expect("event cgroup");
            let target = parts.next().unwrap_or("");
            let target = if target == "-" { String::new() } else { target.to_string() };
            run.events.push(EventLine { hook_type, verdict, cgroup, target });
            continue;
        }
        if let Some(rest) = line.strip_prefix("MISMATCH ") {
            run.mismatches.push(rest.to_string());
            continue;
        }
        if line == "SELFTEST ok" {
            selftest_seen = true;
            run.selftest = Selftest::Ok;
            continue;
        }
        if let Some(rest) = line.strip_prefix("SELFTEST failed ") {
            selftest_seen = true;
            run.selftest = Selftest::Failed(rest.parse().expect("failure count"));
            continue;
        }
        panic!("unrecognised harness line: {line}");
    }

    assert!(shim_seen, "the report must open with the SHIM banner");
    assert!(selftest_seen, "the report must close with a SELFTEST line");
    run
}

/// Parses the body of a `CASE` or `BATCH` line. Both carry the same
/// `key=value` probe fields; the clean fixture terminates with `-> verdict`
/// and batch lines with `verdict=allow|deny`. One parser for both keeps the
/// two grammars from drifting apart.
pub fn parse_case(rest: &str) -> Case {
    let tokens: Vec<&str> = rest.split(' ').collect();
    let number: u64 = tokens[0].parse().expect("case number");
    let hook = CaseHook::from_word(tokens[1]);
    let mut case = Case {
        number,
        hook,
        cgroup: 0,
        ino: 0,
        sha: String::new(),
        flags: 0,
        path: String::new(),
        family: 0,
        addr: 0,
        allow: None,
    };
    let mut index = 2;
    while index < tokens.len() {
        if tokens[index] == "->" {
            case.allow = Some(match tokens[index + 1] {
                "allow" => true,
                "deny" => false,
                other => panic!("case {number}: unknown verdict `{other}`"),
            });
            break;
        }
        let (key, value) = tokens[index]
            .split_once('=')
            .unwrap_or_else(|| panic!("case {number}: field `{}` is not key=value", tokens[index]));
        match key {
            "cg" => case.cgroup = value.parse().expect("cg"),
            "ino" => case.ino = value.parse().expect("ino"),
            "sha" => case.sha = value.to_string(),
            "flags" => case.flags = value.parse().expect("flags"),
            "path" => case.path = value.to_string(),
            "family" => case.family = value.parse().expect("family"),
            "addr" => case.addr = value.parse().expect("addr"),
            "verdict" => {
                case.allow = Some(match value {
                    "allow" => true,
                    "deny" => false,
                    other => panic!("case {number}: unknown verdict `{other}`"),
                });
            }
            other => panic!("case {number}: unknown field `{other}`"),
        }
        index += 1;
    }
    assert!(
        case.allow.is_some(),
        "case {number}: no verdict (`-> allow|deny` or `verdict=allow|deny`)"
    );
    case
}

