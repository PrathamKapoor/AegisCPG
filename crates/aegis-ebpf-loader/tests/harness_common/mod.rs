/// A NULL path from the C harness (case 14: `d_path` failed) replays as the
/// empty string. Both reject it before the trie -- the C because it cannot
/// resolve the path, the models because nothing matches the empty key -- and
/// the verdict the operator sees is the same.
pub fn replay_path(case: &Case) -> &str {
    if case.path == "(null)" {
        ""
    } else {
        &case.path
    }
}

/// The report prints `s_addr` as an integer, which stores the first octet in
/// the low byte; the simulator takes a dotted quad.
pub fn dotted_address(address: u64) -> String {
    format!(
        "{}.{}.{}.{}",
        address as u8,
        (address >> 8) as u8,
        (address >> 16) as u8,
        (address >> 24) as u8
    )
}

pub fn replay_simulator(simulator: &mut KernelLsmSimulator, case: &Case) -> (Verdict, HookType, u64) {
    let (verdict, event) = match case.hook {
        CaseHook::Bprm => simulator.bprm_check_security(case.cgroup, "exec", &case.sha, COMM),
        CaseHook::FileOpen => {
            // O_WRONLY | O_RDWR == 3, exactly as the C hook reads `f_flags`.
            let write = case.flags & 1 != 0 || case.flags & 2 != 0;
            simulator.file_open(case.cgroup, replay_path(case), write, COMM)
        }
        CaseHook::Socket => {
            simulator.socket_connect(case.cgroup, &dotted_address(case.addr), 0, COMM)
        }
    };
    (verdict, event.hook_type, event.cgroup_id)
}

pub fn replay_vm(maps: &mut MapTable, case: &Case) -> bool {
    let (assembly, context) = match case.hook {
        CaseHook::Bprm => (BPRM_CHECK_SECURITY_ASM, bprm_context(case.cgroup, case.ino)),
        CaseHook::FileOpen => (
            FILE_OPEN_ASM,
            file_open_context(case.cgroup, case.flags, replay_path(case)),
        ),
        CaseHook::Socket => (
            SOCKET_CONNECT_ASM,
            socket_context(case.cgroup, case.family, case.addr as u32),
        ),
    };
    Vm::new(maps)
        .run(program_for(assembly), &context)
        .expect("the decision program must execute") == 0
}

static BPRM_PROGRAM: OnceLock<Vec<u8>> = OnceLock::new();
static FILE_OPEN_PROGRAM: OnceLock<Vec<u8>> = OnceLock::new();
static SOCKET_PROGRAM: OnceLock<Vec<u8>> = OnceLock::new();

/// The assembled bytes of one decision program.
///
/// `Vm::run_assembly` re-parses the same static text on every call; the
/// differential fuzzer replays 14,000 probes twice, so the text is assembled
/// once and every probe after the first runs the bytecode through decode,
/// verify, and execute. A program that fails to assemble panics once, here,
/// instead of being retried per probe.
fn program_for(assembly: &'static str) -> &'static [u8] {
    let slot = match assembly {
        BPRM_CHECK_SECURITY_ASM => &BPRM_PROGRAM,
        FILE_OPEN_ASM => &FILE_OPEN_PROGRAM,
        SOCKET_CONNECT_ASM => &SOCKET_PROGRAM,
        other => panic!(
            "no cached assembly for program {:?}",
            &other[..other.len().min(32)]
        ),
    };
    slot.get_or_init(|| assemble(assembly).expect("the decision program must assemble"))
}

pub fn bprm_context(cgroup: u64, inode: u64) -> Vec<u8> {
    let mut context = cgroup.to_le_bytes().to_vec();
    context.extend_from_slice(&inode.to_le_bytes());
    context
}

pub fn file_open_context(cgroup: u64, flags: u64, path: &str) -> Vec<u8> {
    let mut context = cgroup.to_le_bytes().to_vec();
    context.extend_from_slice(&flags.to_le_bytes());
    let mut data = [0u8; 128];
    data[..path.len()].copy_from_slice(path.as_bytes());
    context.extend_from_slice(&data);
    context
}

pub fn socket_context(cgroup: u64, family: u64, address: u32) -> Vec<u8> {
    let mut context = cgroup.to_le_bytes().to_vec();
    context.extend_from_slice(&u64::from(address).to_le_bytes());
    context.extend_from_slice(&family.to_le_bytes());
    context
}
