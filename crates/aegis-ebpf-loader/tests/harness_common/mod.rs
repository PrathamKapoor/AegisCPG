//! Shared machinery for the native-shim test binaries.
//!
//! **Author:** Pratham Kapoor `<prathamkapoor027@gmail.com>`
//! **Repository:** <https://github.com/PrathamKapoor>
//!
//! ## WHAT
//! Builds `ebpf-probes/aegis_userspace_shim.c` -- which compiles the real
//! `ebpf-probes/lsm_enforcer.bpf.c` hooks as native C -- with the in-repo LLVM,
//! runs it, parses its machine-readable report, and turns either the report's
//! own `MAP` lines or a generated map table of the same shape into the two
//! Rust re-implementations of the decision table: the reference simulator
//! ([`KernelLsmSimulator`]) and the RFC 9669 BPF VM ([`Vm`]).
//!
//! ## WHY
//! `shim_equivalence.rs` (the pinned 24-case table and its five fail-open
//! mutations) and `differential_fuzz.rs` (1,000 seeded cases driven through
//! the same C binary in one batch) must execute the same artefact with the
//! same replay code; a second copy of the builder would be a second thing to
//! drift. The side that cannot drift silently is the one that gets to exist.
//!
//! ## HOW
//! `clang --target=aarch64-pc-windows-msvc -O1 -ffreestanding ...` compiles
//! the shim into `target/<root_name>/<name>/`; `lld-link` links it against a
//! kernel32 import library that `llvm-dlltool` generates from a `.def` written
//! here (four symbols; `ReadFile` is referenced only by the batch build).
//! Extra `-D` defines are appended to the compile line, which is how
//! `-DAEGIS_SHIM_BATCH` opens the stdin-driven fuzzer mode. Nothing is skipped
//! on any host: a missing toolchain fails loudly through
//! [`toolchain::require_llvm_tool`], never silently.
#![allow(dead_code)] // Each test binary compiles this module and uses a subset.

