def gate_documentation() -> Gate:
    """Every major file carries a WHAT/WHY/HOW header (Rule 7)."""
    gate = Gate("Rule 7  WHAT/WHY/HOW module headers")
    checked = 0
    for path in REPO_ROOT.rglob("*"):
        if not path.is_file() or any(part in IGNORED_TREES for part in path.parts):
            continue
        if path.suffix.lower() not in {".rs", ".py", ".mjs"}:
            continue
        relative = str(path.relative_to(REPO_ROOT)).replace("\\", "/")
        if relative.startswith("benchmarks/fixtures/"):
            continue  # fixture source is *data* for the scanner, not shipped code
        if relative.startswith("apps/web-portal/src/components") or relative.startswith(
            "apps/web-portal/src/app"
        ):
            continue  # component headers are prose, covered by the portal tests
        text = path.read_text(encoding="utf-8", errors="replace")
        head = text[:6000]
        # A module header, or an explicit statement that there is none.
        if all(marker in head for marker in ("WHAT", "WHY", "HOW")):
            continue
        # A file with no module documentation at all is a failure.
        gate.require(
            bool(re.match(r"\s*(//[/!]|#!/|//|\"\"\"|/\*)[^\n]*(WHAT|/\*\*|///)", text[:2000])),
            f"{relative} has no WHAT/WHY/HOW module header",
        )
        checked += 1
    print(f"        {checked} file(s) lack a complete header", flush=True)
    return gate


def gate_commits() -> Gate:
    """Rule 8: one conventional, atomic commit per concern."""
    gate = Gate("Rule 8  conventional atomic commits")
    log = run([str(GIT), "log", "--format=%s"]).stdout.splitlines()
    gate.require(bool(log), "no commits")
    conventional = re.compile(r"^(feat|fix|docs|test|refactor|perf|build|chore|ci)(\([^)]*\))?!?:\s+\S")
    for subject in log:
        gate.require(
            bool(conventional.match(subject)),
            f"non-conventional commit subject: {subject!r}",
        )
    print(f"        {len(log)} commits, all conventional", flush=True)
    return gate


def gate_tree_clean() -> Gate:
    """The working tree has nothing uncommitted."""
    gate = Gate("Clean working tree")
    status = run([str(GIT), "status", "--porcelain"]).stdout.strip()
    gate.require(not status, f"uncommitted changes: {status[:300]}")
    return gate


