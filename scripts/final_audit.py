def main() -> int:
    started = time.time()
    print("=" * 78)
    print("AegisCPG final audit")
    print(f"repository : {REPO_ROOT}")
    print(f"interpreter: {sys.executable}")
    print("=" * 78)

    results: list[tuple[Gate, str, str]] = []
    for factory in GATES:
        print(f"\n[{factory.__name__}]", flush=True)
        try:
            gate = factory()
        except Exception as error:  # a gate that crashes is a failed gate
            gate = Gate(factory.__name__)
            gate.failures.append(f"the gate raised {type(error).__name__}: {error}")
        results.append((gate, *gate.result()))
        for failure in gate.failures:
            print(f"    - {failure}", flush=True)

    print("\n" + "=" * 78)
    width = max(len(name) for _, name, _ in results)
    for gate, status, detail in results:
        line = f"{status:<5} {gate.name:<{width}}"
        print(f"{line}  {detail}".rstrip())
    failed = [g for g, s, _ in results if s == "FAIL"]
    elapsed = time.time() - started
    print("=" * 78)
    if failed:
        print(f"AUDIT FAILED: {len(failed)} of {len(results)} gates did not pass ({elapsed:.1f}s)")
        return 1
    print(f"AUDIT PASSED: {len(results)} of {len(results)} gates ({elapsed:.1f}s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
