def gate_benchmarks() -> Gate:
    """Rule 10: the benchmark harness re-runs and meets every threshold.

    Runs with ``--no-persist`` so the audit *verifies* the committed reference
    results rather than overwriting them. A benchmark run that rewrote
    `summary_metrics.json` would leave the tree dirty, and the clean-tree gate
    would then fail on the audit's own output -- which is a gate that measures
    the wrong thing.
    """
    gate = Gate("Rule 10 reproducible benchmarks")
    gate.require(CLI.exists(), f"{CLI} is not built")
    if not CLI.exists():
        return gate
    completed = run(
        [str(PYTHON), "benchmarks/run_all_benchmarks.py", "--no-persist"], timeout=3600
    )
    summary_path = REPO_ROOT / "benchmarks" / "results" / "summary_metrics.json"
    gate.require(summary_path.exists(), "no summary_metrics.json is committed")
    if not summary_path.exists():
        return gate
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    gate.require(completed.returncode == 0, f"the harness exited {completed.returncode}")
    gate.require(
        summary["threshold_failures"] == [],
        f"the committed run reported threshold failures: {summary['threshold_failures']}",
    )
    static = summary["static"]
    gate.require(static["recall_count"] == 9, f"recall {static['recall_count']}/9")
    gate.require(static["false_positive_count"] == 0, f"{static['false_positive_count']}/5 false positives")
    gate.require(static["min_compression_ratio"] >= 0.80, "compression below the hop bound")
    gate.require(summary["chains"]["blocked"] == summary["chains"]["malicious"], "a malicious chain survived")
    gate.require(
        summary["divergence"]["max_benign_score"] < summary["divergence"]["threshold"],
        "a benign fixture scored above the divergence threshold",
    )
    database = REPO_ROOT / "benchmarks" / "results" / "aegis_benchmarks.duckdb"
    parquet = REPO_ROOT / "benchmarks" / "results" / "aegis_benchmarks.parquet"
    gate.require(database.exists() and database.stat().st_size > 0, "no DuckDB output")
    gate.require(parquet.exists() and parquet.stat().st_size > 0, "no Parquet output")
    print(
        f"        recall {static['recall_count']}/9, fpr {static['false_positive_count']}/5, "
        f"compression {static['min_compression_ratio'] * 100:.2f}%+, "
        f"chains {summary['chains']['blocked']}/{summary['chains']['malicious']}",
        flush=True,
    )
    return gate


