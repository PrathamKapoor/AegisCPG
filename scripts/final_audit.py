"""AegisCPG final audit.

Author: Pratham Kapoor <prathamkapoor027@gmail.com>
https://github.com/PrathamKapoor

WHAT
    Runs every gate in one pass and prints a pass/fail line for each, so a
    reviewer can confirm the whole repository in a single command rather than
    by reading four CI configs and trusting them to agree.

WHY ONE COMMAND
    The Hard Rules are not independent. Rule 1 (everything contained) is
    asserted by the path walk. Rule 2 (sole authorship) by the git log. Rule 3
    (no stubs) by the placeholder scan. Rule 4 (zero LLM) by both the manifest
    scan and the dependency walk. Rule 10 (measured, not asserted) by
    re-running the benchmark and checking the README against its output. A
    repository where the gates drift apart is one where none of them holds.

HOW
    Each gate is a function returning a list of failures. A gate that cannot run
    -- the CLI is not built, say -- is a *failure*, not a skip: an audit that
    silently skips is not an audit.

Run: python scripts/final_audit.py
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CLI = REPO_ROOT / "target" / "debug" / ("aegis-cli.exe" if os.name == "nt" else "aegis-cli")
CARGO_WRAPPER = REPO_ROOT / ".toolchain" / "cargo.ps1"
PYTHON = REPO_ROOT / ".toolchain" / "python" / "python.exe"
GIT = REPO_ROOT / ".toolchain" / "git" / "cmd" / "git.exe"

#: Directories that legitimately contain vendored or generated bytes.
IGNORED_TREES = {".toolchain", "target", ".git", "node_modules", "__pycache__", ".mlcache"}
IGNORED_SUFFIXES = {".exe", ".dll", ".obj", ".lib", ".pyd", ".onnx", ".parquet", ".pyc", ".whl"}

#: Words that indicate unfinished work. Matched case-insensitively, with word
#: boundaries, and excluding this repository's own prose about stubs -- which it
#: has to have, since the post-mortems describe the defects by name.
PLACEHOLDER_PATTERNS = (
    r"\bTODO\b",
    r"\bFIXME\b",
    r"\bXXX\b",
    r"\bHACK\b",
    r"\bnot implemented\b",
    r"\bunimplemented!",
    r"\bplaceholder\b",
    r"\bcoming soon\b",
    r"\bstub\b",
    r"\bdummy\b",
    r"\bfake it\b",
    r"\bfor now\b",
)
#: Files whose text legitimately contains those words when *describing* the rule.
PLACEHOLDER_EXEMPT = {
    "scripts/final_audit.py",
    "README.md",
    "decisions.md",
    "flow.md",
    ".gitignore",
}

#: The only permitted author identity.
EXPECTED_AUTHOR = "PrathamKapoor <prathamkapoor027@gmail.com>"

#: Generative runtimes that must not appear anywhere in the control plane.
LLM_TOKENS = (
    "torch",
    "tensorflow",
    "transformers",
    "openai",
    "anthropic",
    "ollama",
    "llama_cpp",
    "langchain",
    "huggingface_hub",
    "sentence_transformers",
    "cohere",
    "mistralai",
    "vertexai",
    "bedrock",
)


class Gate:
    """One named check, accumulating failures."""

    def __init__(self, name: str) -> None:
        self.name = name
        self.failures: list[str] = []
        self.skipped = False

    def require(self, condition: bool, message: str) -> None:
        if not condition:
            self.failures.append(message)

    def result(self) -> tuple[str, str]:
        if self.skipped:
            return "SKIP", f"{len(self.failures)} failure(s)"
        if self.failures:
            return "FAIL", f"{len(self.failures)} failure(s)"
        return "PASS", ""


def run(command: list[str], timeout: int = 1800) -> subprocess.CompletedProcess:
    return subprocess.run(
        command, capture_output=True, text=True, timeout=timeout, cwd=str(REPO_ROOT)
    )


